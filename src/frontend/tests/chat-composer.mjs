import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { expect } from "@playwright/test";

export async function verifyChatComposer({ page, call, state, until, org, directory }) {
  assert(process.env.AE_TEST_ORG && path.resolve(org) !== path.resolve("../../org"), "Use a disposable organization");
  const input = page.getByRole("textbox", { name: "Message", exact: true });
  const send = page.getByRole("button", { name: "Send message", exact: true });
  const members = page.getByRole("button", { name: "View group agents" });
  const list = page.getByRole("list", { name: "Group agents" });
  const height = async () => (await input.boundingBox()).height;
  const initialHeight = await height();
  assert(initialHeight >= 42 && initialHeight <= 46, `Compact height: ${initialHeight}`);
  assert(await page.evaluate(() => CSS.supports("field-sizing", "content")));
  await expect(page.getByText("Send directly", { exact: true })).toHaveCount(0);
  await expect(send).toBeDisabled();
  await input.fill("First line");
  await input.press("Shift+Enter");
  await input.press("a");
  assert(await height() > initialHeight, "New lines grow the composer");
  await input.fill("Long wrapping text ".repeat(40));
  assert(await height() > initialHeight, "Wrapped lines grow the composer");
  await input.fill(Array.from({ length: 40 }, (_, i) => `Line ${i + 1}`).join("\n"));
  const cappedHeight = await height();
  assert(cappedHeight <= 220 && cappedHeight >= 200);
  assert(await input.evaluate((el) => el.scrollHeight > el.clientHeight && getComputedStyle(el).overflowY === "auto"));
  await page.screenshot({ path: path.join(directory, "composer-expanded.png") });
  await input.fill("");
  assert.equal(await height(), initialHeight, "Deleting text shrinks the composer");
  const hint = await page.locator(".chat-lead-hint").boundingBox();
  const button = await send.boundingBox();
  assert(hint.x + hint.width < button.x && Math.abs(hint.y + hint.height / 2 - button.y - button.height / 2) < 2, "Hint is left of Send on the same row");
  assert((await members.boundingBox()).x < (await page.getByRole("button", { name: "Manage group" }).boundingBox()).x);

  const workspace = path.join(org, "composer-workdir");
  await mkdir(workspace, { recursive: true });
  const workdir = (await call("/workspaces/probe", { path: workspace })).workspace;
  const original = (await state()).agents.find((a) => a.id === "ceo");
  const catalog = await call("/codex/settings", undefined, "GET");
  const first = await call("/agents/ceo", { ...original, name: "Agent A", position: "Director", workdir, reasoning: "low", model: catalog.models.find((m) => m.slug === "gpt-5.6-luna")?.slug ?? catalog.model, instructions: "Respond with the exact requested text. No tools or delegation." }, "PUT");
  const second = await call("/agents", { ...first, id: "", name: "Agent B", position: "Advisor", reports_to: null });
  const worker = await call("/agents", { ...first, id: "", name: "Scoped Worker", position: "Engineer", reports_to: first.id });
  const paused = await call("/agents", { ...first, id: "", name: "Paused Agent", enabled: false, reports_to: null });
  await page.reload();
  await members.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("dialog", { name: "Agents in General" })).toBeVisible();
  await expect(list.getByRole("listitem")).toHaveCount(4);
  await expect(list.getByRole("listitem").filter({ has: page.getByText(first.name, { exact: true }) }).getByText("Director", { exact: true })).toBeVisible();
  await expect(list.getByText("Chat lead", { exact: true })).toBeVisible();
  await expect(list.getByText("Paused", { exact: true })).toBeVisible();
  await page.screenshot({ path: path.join(directory, "group-agents-dialog.png") });
  await page.keyboard.press("Escape");
  await expect(members).toBeFocused();
  await input.fill("@Agent A, @Agent B Reply exactly COMPOSER_MENTIONS_OK.");
  await expect(page.locator(".chat-lead-hint")).toHaveText("Sending to Agent A, Agent B.");
  await send.click();
  await expect(input).toHaveValue("");
  assert.equal(await height(), initialHeight, "Sending resets height");
  const message = await until(async () => (await call("/groups/general/messages", undefined, "GET")).find((m) => m.body.startsWith("@Agent A, @Agent B")));
  assert.deepEqual(message.recipients.sort(), [first.id, second.id].sort());
  const runs = await until(async () => {
    const matches = (await state()).runs.filter((r) => r.message_id === message.id);
    return matches.length === 2 && matches.every((r) => !["queued", "starting", "running", "waiting"].includes(r.status)) && matches;
  });
  assert(runs.every((r) => r.status === "succeeded" && r.output.includes("COMPOSER_MENTIONS_OK")), JSON.stringify(runs.map((r) => ({ id: r.id, status: r.status, error: r.error }))));
  const ownerBubble = page.locator(".message-owner .message-bubble").last();
  const agentBubble = page.locator(".message-agent .message-bubble").last();
  await expect(ownerBubble).toHaveCSS("background-color", "rgb(20, 86, 199)");
  await expect(ownerBubble.locator(".markdown")).toHaveCSS("color", "rgb(255, 255, 255)");
  await expect(agentBubble).toContainText("COMPOSER_MENTIONS_OK");
  assert((await agentBubble.evaluate((el) => getComputedStyle(el).backgroundImage)).includes("linear-gradient"));
  await page.screenshot({ path: path.join(directory, "chat-bubbles-main.png"), animations: "disabled" });
  await input.fill("/btw");
  await input.press("Enter");
  await expect(page.getByRole("region", { name: "Side chat" })).toBeVisible();
  assert.equal(await height(), initialHeight);
  await input.fill("Side line\nAnother line");
  assert(await height() > initialHeight);
  await input.fill("");
  await input.fill("@Agent A Reply exactly SIDE_BUBBLE_OK. Do not open links or use tools.\n\n**Display check:** [Reference](https://example.com), `inline code`.\n\n```text\n" + "long_value_".repeat(30) + "\n```\n\n| Item | State |\n| --- | --- |\n| Bubble | Ready |");
  await send.click();
  await until(async () => (await state()).runs.some((r) => r.side_chat_id && r.status === "succeeded" && r.output.includes("SIDE_BUBBLE_OK")));
  await expect(agentBubble).toContainText("SIDE_BUBBLE_OK");
  await expect(ownerBubble.locator(".markdown a")).toHaveCSS("color", "rgb(255, 255, 255)");
  await expect(ownerBubble.locator("pre")).toBeVisible();
  await expect(ownerBubble.locator("table")).toBeVisible();
  await page.reload();
  await expect(page.getByRole("region", { name: "Side chat" })).toBeVisible();
  await expect(agentBubble).toContainText("SIDE_BUBBLE_OK");
  await page.setViewportSize({ width: 775, height: 900 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Long code and tables stay inside narrow side bubbles");
  await page.screenshot({ path: path.join(directory, "chat-bubbles-side.png"), animations: "disabled" });
  await page.setViewportSize({ width: 1440, height: 980 });
  await page.getByRole("button", { name: "Back to main chat" }).click();

  const general = (await state()).groups.find((g) => g.id === "general");
  await call("/groups", { ...general, scope_levels: [1] });
  await page.reload();
  await members.click();
  await expect(list.getByRole("listitem")).toHaveCount(3);
  await expect(list.getByText(worker.name, { exact: true })).toHaveCount(0);
  await expect(list.getByText(paused.name, { exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await input.fill(`@${worker.name} Not allowed in this group.`);
  await send.click();
  await expect(page.getByRole("alert")).toContainText("outside this group's chat scope");
  await input.fill("");
  await page.getByRole("button", { name: "Dismiss error" }).click();
  await input.fill("/");
  await expect(page.getByRole("listbox", { name: "Chat commands" }).getByRole("option")).toHaveCount(3);
  await input.press("Escape");
  await input.fill("");
  await page.screenshot({ path: path.join(directory, "composer-compact.png") });
  await page.setViewportSize({ width: 775, height: 700 });
  await expect(members).toBeVisible();
  await members.click();
  await expect(list).toBeVisible();
  const modal = await page.getByRole("dialog").boundingBox();
  assert(modal.width <= 420 && modal.x >= 0 && modal.x + modal.width <= 775);
  await page.keyboard.press("Escape");
  await input.fill("Many lines\n".repeat(40));
  assert(await height() <= 210, "Height cap follows a shorter viewport");
  await expect(send).toBeInViewport();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "No page overflow");
  await input.fill("");
  await page.screenshot({ path: path.join(directory, "composer-narrow.png") });
  return { initialHeight, cappedHeight, mentions: message.recipients, runs: runs.map((r) => r.id), scopedMembers: 3, sharedSideComposer: true, mainAndSideBubbles: true, persistedSideReply: true, narrowViewport: true, mocks: "none" };
}
