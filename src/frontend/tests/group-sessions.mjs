import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { expect } from "@playwright/test";

export async function verifyGroupSessions({ page, request, call, state, until, finished, org, directory }) {
  assert(process.env.AE_TEST_ORG && path.resolve(org) !== path.resolve("../../org"), "Use a fresh disposable organization");
  page.setDefaultTimeout(20000);
  const sessions = () => call("/sessions", undefined, "GET");
  const allMessages = () => call("/groups/general/messages", undefined, "GET");
  const send = (body, group_id = "general", extra = {}) => call("/messages", { id: crypto.randomUUID(), body, group_id, recipients: ["ceo"], ...extra });
  const configureWorkdir = async (name) => { const folder = path.join(org, name); await mkdir(folder); return (await call("/workspaces/probe", { path: folder })).workspace; };
  assert.equal((await sessions()).length, 0);
  const original = (await state()).agents.find((a) => a.id === "ceo");
  const catalog = await call("/codex/settings", undefined, "GET");
  const leader = await call("/agents/ceo", { ...original, workdir: await configureWorkdir("leader"), permission: "danger-full-access", model: catalog.models.find((m) => m.slug === "gpt-5.6-luna")?.slug ?? catalog.model, reasoning: "low", timeout_seconds: 240, instructions: "Answer using the supplied conversation context. Remember codes the owner provides for this conversation. Never guess a code. If not present say UNKNOWN. Use tools only when explicitly asked. Delegate only when explicitly asked." }, "PUT");
  const worker = await call("/agents", { ...leader, id: "", name: "Worker", reports_to: leader.id, workdir: await configureWorkdir("worker") });
  const idle = await call("/agents", { ...leader, id: "", name: "Never triggered", reports_to: leader.id, workdir: await configureWorkdir("idle") });
  const groupB = await call("/groups", { id: "", name: "Separate group", description: "Session isolation verification" });
  assert.equal((await sessions()).length, 0, "Creating groups/agents never starts sessions");
  const alpha = `MAIN_${crypto.randomUUID()}`;
  const beta = `OTHER_${crypto.randomUUID()}`;
  const gamma = `SIDE_${crypto.randomUUID()}`;
  const a = await finished((await send(`Remember this group's MAIN code ${alpha}. Reply exactly that code.`)).id);
  assert.equal(a.status, "succeeded", a.error);
  assert(a.output.includes(alpha));
  assert.equal((await sessions()).length, 1);
  const b = await finished((await send(`Remember this group's OTHER code ${beta}. Reply exactly that code.`, groupB.id)).id);
  assert.equal(b.status, "succeeded", b.error);
  assert.notEqual(a.native_session_id, b.native_session_id);
  assert.equal((await sessions()).length, 2);
  await page.goto("/groups/general/chat");
  const input = page.getByRole("textbox", { name: "Message", exact: true });
  await input.fill("/");
  await expect(page.getByRole("listbox", { name: "Chat commands" }).getByRole("option")).toHaveCount(3);
  await input.fill("/btw");
  const before = (await state()).runs.length;
  await input.press("Enter");
  await expect(page).toHaveURL(/\/groups\/general\/chat\?side=/);
  await expect(page.getByRole("region", { name: "Side chat", exact: true })).toBeVisible();
  const side = (await allMessages()).find((m) => m.command === "btw");
  assert.equal((await state()).runs.length, before);
  assert.equal((await sessions()).length, 2, "Empty side chat creates no agent session");
  await call("/messages", { id: side.id, group_id: "general", body: "/btw" });
  assert.equal((await allMessages()).filter((m) => m.id === side.id).length, 1);
  const hold = await call("/agents/ceo/terminal", { id: crypto.randomUUID(), command: "Start-Sleep -Seconds 7; Write-Output 'QUEUE_RELEASE'" });
  await input.fill(`What MAIN code did I give in this group? Reply with it. Remember this group's SIDE code ${gamma} for later.`);
  await input.press("Enter");
  const question = await until(async () => (await allMessages()).find((m) => m.side_chat_id === side.id && m.id !== side.id && m.sender === "owner"));
  const queued = (await state()).runs.find((r) => r.message_id === question.id);
  assert.equal(queued.status, "queued");
  assert.notEqual(queued.session_id, a.session_id);
  assert.equal((await request.post("/api/messages", { data: { id: crypto.randomUUID(), group_id: "general", body: "/reset", side_chat_id: side.id } })).status(), 400);
  await send("/reset", groupB.id, { recipients: [] });
  assert((await sessions()).find((s) => s.id === a.session_id).active);
  assert(!(await sessions()).find((s) => s.id === b.session_id).active);
  const sideRun = await finished(question.id);
  assert.equal(sideRun.status, "succeeded", sideRun.error);
  assert.notEqual(sideRun.native_session_id, a.native_session_id);
  assert(sideRun.output.includes(alpha), "Side chat must know the main context");
  await until(async () => (await call(`/agents/ceo/terminal/${hold.id}`, undefined, "GET")).status === "completed", 20000);
  const reply = (await allMessages()).find((m) => m.run_id === sideRun.id);
  assert.equal(reply.side_chat_id, side.id);
  await expect(page.locator(".message").filter({ hasText: sideRun.output })).toBeVisible();
  await page.screenshot({ path: path.join(directory, "independent-side-chat.png"), animations: "disabled" });
  await page.getByRole("button", { name: "Back to main chat", exact: true }).click();
  await expect(page).toHaveURL(/\/groups\/general\/chat$/);
  const main = await call("/groups/general/messages?main=true", undefined, "GET");
  assert(main.some((m) => m.id === side.id));
  assert(!main.some((m) => m.id === reply.id));
  await expect(page.getByRole("button", { name: "Open side chat", exact: true })).toBeVisible();
  const recall = await finished((await send("What is the SIDE code from the side conversation? If absent reply UNKNOWN. Do not guess or use tools.")).id);
  assert.equal(recall.status, "succeeded", recall.error);
  assert(!recall.output.includes(gamma) && recall.output.includes("UNKNOWN"), "Main must not receive side context");
  assert.equal(recall.native_session_id, a.native_session_id);
  const continued = await finished((await send("Reply exactly the SIDE code I gave you. Do not use tools.", "general", { side_chat_id: side.id })).id);
  assert.equal(continued.status, "succeeded", continued.error);
  assert(continued.output.includes(gamma));
  assert.equal(continued.native_session_id, sideRun.native_session_id);

  // Both Codex processes hold different marker files in the same attached workdir.
  // Releasing the side must let its queued follow-up finish while main remains blocked.
  const gate = (name) => ({ ready: path.join(leader.workdir.path, `${name}.ready`), release: path.join(leader.workdir.path, `${name}.release`) });
  const mainGate = gate("main");
  const sideGate = gate("side");
  const quote = (value) => `'${value.replaceAll("'", "''")}'`;
  const holdTask = (g) => `Execute exactly this PowerShell command using your shell tool and wait for its real output: Set-Content -LiteralPath ${quote(g.ready)} -Value READY; $deadline=(Get-Date).AddSeconds(90); while (-not (Test-Path -LiteralPath ${quote(g.release)})) { if ((Get-Date) -gt $deadline) { throw 'Gate timed out' }; Start-Sleep -Milliseconds 200 }; Write-Output GATE_RELEASED. Reply GATE_RELEASED only after the command finishes. These are authorized verification files in your attached workdir.`;
  const mainHold = await send(holdTask(mainGate));
  await until(async () => existsSync(mainGate.ready), 60000);
  const mainQueued = await send("Reply exactly MAIN_QUEUE_DONE. No tools needed.");
  const sideHold = await send(holdTask(sideGate), "general", { side_chat_id: side.id });
  await until(async () => existsSync(sideGate.ready), 60000);
  const sideQueued = await send("Reply exactly SIDE_QUEUE_DONE. No tools needed.", "general", { side_chat_id: side.id });
  const snapshot = (await state()).runs;
  const mainLive = snapshot.find((r) => r.message_id === mainHold.id);
  const sideLive = snapshot.find((r) => r.message_id === sideHold.id);
  assert.equal(mainLive.status, "running");
  assert.equal(sideLive.status, "running");
  assert.notEqual(mainLive.session_id, sideLive.session_id);
  assert.equal(mainLive.cwd, sideLive.cwd);
  assert.equal(snapshot.find((r) => r.message_id === mainQueued.id).status, "queued");
  assert.equal(snapshot.find((r) => r.message_id === sideQueued.id).status, "queued");
  const liveCount = execFileSync("pwsh", ["-NoProfile", "-Command", `@(Get-Process -Id ${mainLive.pid},${sideLive.pid} -ErrorAction Stop | Where-Object { $_.ProcessName -eq 'codex' }).Count`], { encoding: "utf8" }).trim();
  assert.equal(liveCount, "2", "Two real native Codex processes must overlap");
  const parallel = { main: mainLive.id, side: sideLive.id, mainPid: mainLive.pid, sidePid: sideLive.pid, cwd: mainLive.cwd, mainSession: mainLive.session_id, sideSession: sideLive.session_id, liveProcesses: 2 };
  await writeFile(path.join(directory, "parallel-side-live.json"), JSON.stringify(parallel, null, 2));
  await writeFile(sideGate.release, "RELEASE");
  assert.equal((await finished(sideHold.id)).status, "succeeded");
  const sideFinished = await finished(sideQueued.id);
  assert.equal(sideFinished.status, "succeeded", sideFinished.error);
  assert(sideFinished.output.includes("SIDE_QUEUE_DONE"));
  assert.equal((await state()).runs.find((r) => r.id === mainLive.id).status, "running");
  assert.equal((await state()).runs.find((r) => r.message_id === mainQueued.id).status, "queued");
  await send("/reset", "general", { recipients: [], side_chat_id: side.id });
  assert((await sessions()).find((s) => s.id === a.session_id).active, "Side reset leaves a running main session active");
  await writeFile(mainGate.release, "RELEASE");
  assert.equal((await finished(mainHold.id)).status, "succeeded");
  assert.equal((await finished(mainQueued.id)).status, "succeeded");
  const freshB = await finished((await send("What is this group's previous OTHER code? If absent reply UNKNOWN. Do not guess or use tools.", groupB.id)).id);
  assert.equal(freshB.status, "succeeded", freshB.error);
  assert.notEqual(freshB.native_session_id, b.native_session_id);
  assert(!freshB.output.includes(beta));
  assert(freshB.output.includes("UNKNOWN"));
  const delegated = await send(`/btw Delegate exactly one task to agent ${worker.id}: reply exactly DELEGATED_SIDE_OK. Then summarize its result.`, "general", { recipients: [] });
  const sideRuns = await until(async () => { const runs = (await state()).runs.filter((r) => r.message_id === delegated.id); return runs.some((r) => r.kind === "summary" && r.status === "succeeded") && runs; }, 300000);
  const child = sideRuns.find((r) => r.kind === "delegate");
  assert.equal(child.agent_id, worker.id);
  assert.equal(child.status, "succeeded", child.error);
  assert(sideRuns.every((r) => r.side_chat_id === delegated.id));
  assert.equal((await sessions()).filter((s) => s.agent_id === worker.id && s.group_id === "general").length, 1);
  assert.equal((await sessions()).filter((s) => s.agent_id === idle.id).length, 0);
  assert((await allMessages()).filter((m) => sideRuns.some((r) => r.id === m.run_id)).every((m) => m.side_chat_id === delegated.id));
  for (const route of [`/groups/${groupB.id}/messages?side_chat_id=${side.id}`, "/groups/general/messages?side_chat_id=missing"]) assert.equal((await request.get(`/api${route}`)).status(), 400);
  assert.equal((await request.post("/api/messages", { data: { id: crypto.randomUUID(), group_id: groupB.id, body: "Wrong group", side_chat_id: side.id } })).status(), 400);
  const anon = await page.context().browser().newContext();
  assert.equal((await anon.request.get(new URL(`/api/groups/general/messages?side_chat_id=${side.id}`, page.url()).href)).status(), 401);
  await anon.close();
  await send("/reset", "general", { recipients: [] });
  assert((await sessions()).filter((s) => s.group_id === "general").every((s) => !s.active));
  assert((await sessions()).find((s) => s.id === freshB.session_id).active);
  const resetRun = await finished((await send("Reply exactly FRESH_SIDE_OK.", "general", { side_chat_id: side.id })).id);
  assert.equal(resetRun.status, "succeeded", resetRun.error);
  assert.notEqual(resetRun.native_session_id, sideRun.native_session_id);
  assert.equal((await sessions()).filter((s) => s.agent_id === idle.id).length, 0);
  for (const script of ["Stop", "Start"]) execFileSync("pwsh", ["-NoProfile", "-File", `../scripts/${script}.ps1`, "-Org", org], { stdio: "ignore", timeout: 25000 });
  await page.goto(`/groups/general/chat?side=${side.id}`);
  await expect(page.getByRole("region", { name: "Side chat", exact: true })).toBeVisible();
  await expect(page.locator(".message").filter({ hasText: "FRESH_SIDE_OK" }).last()).toBeVisible();
  await page.goto("/organization/agents/ceo/sessions");
  await expect(page.getByText("Idle · resumes when triggered").first()).toBeVisible();
  const pids = (await state()).runs.map((r) => r.pid).filter(Boolean);
  const live = execFileSync("pwsh", ["-NoProfile", "-Command", `$p = @(Get-Process -Id ${pids.join(",")} -ErrorAction SilentlyContinue | Where-Object { $_.ProcessName -eq 'codex' }); Write-Output $p.Count`], { encoding: "utf8" }).trim();
  assert.equal(live, "0", "Finished executions must not retain Codex processes");
  assert(existsSync(path.join(org, ".state/runtime/ceo/side-chats", side.id, "codex/sessions")), "Side runtime is isolated from main Codex home");
  const proof = { groupA: "general", groupB: groupB.id, initialA: a.id, initialB: b.id, independentSideRun: sideRun.id, isolatedMainRun: recall.id, sideContinuation: continued.id, parallel, otherGroupFreshRun: freshB.id, delegateRun: child.id, resetSideRun: resetRun.id, idleAgentSessions: 0, liveCodexProcesses: 0, sideRoot: side.id, restartPersisted: true, mocks: "none" };
  await writeFile(path.join(directory, "group-sessions-proof.json"), JSON.stringify(proof, null, 2));
  return proof;
}
