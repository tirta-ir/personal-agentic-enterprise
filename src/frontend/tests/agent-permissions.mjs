import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { expect } from "@playwright/test";

export async function verifyAgentPermissions({ page, request, call, state, until, finished, org, directory }) {
  assert(process.env.AE_TEST_ORG && path.resolve(org) !== path.resolve("../../org"), "Use an isolated organization");
  const workspace = path.join(org, "permission workdir");
  await mkdir(workspace, { recursive: true });
  const original = (await state()).agents.find((a) => a.id === "ceo");
  assert.equal(original.permission, "read-only", "New organization default stays read-only");
  const catalog = await call("/codex/settings", undefined, "GET");
  let agent = await call("/agents/ceo", { ...original, workdir: (await call("/workspaces/probe", { path: workspace })).workspace, model: catalog.models.find((m) => m.slug === "gpt-5.6-luna")?.slug ?? catalog.model, reasoning: "low", instructions: "Execute the owner's requested verification command exactly. Use your shell tool and report actual evidence. Do not delegate unless explicitly requested.", timeout_seconds: 240 }, "PUT");
  await page.goto("/organization/agents/ceo/workdir");
  const access = page.getByLabel("Access mode", { exact: true });
  assert.deepEqual(await access.locator("option").evaluateAll((options) => options.map((o) => o.value)), ["read-only", "workspace-write", "danger-full-access"]);
  const setMode = async (permission) => {
    await access.selectOption(permission);
    await page.getByRole("button", { name: "Change workdir", exact: true }).click();
    agent = await until(async () => { const a = (await state()).agents.find((a) => a.id === "ceo"); return a.permission === permission && a; }, 10000);
    await page.reload();
    await expect(access).toHaveValue(permission);
  };
  const runFile = async (target, marker, permission) => {
    const ps = (s) => `'${s.replaceAll("'", "''")}'`;
    const command = `[System.IO.File]::WriteAllText(${ps(target)}, ${ps(marker)}); Get-Content -LiteralPath ${ps(target)}`;
    const message = await call("/messages", { id: crypto.randomUUID(), group_id: "general", body: `Use the PowerShell shell tool to execute exactly this command, then return the actual marker read from the file: ${command}. This is an owner-authorized verification file inside the disposable test organization.`, recipients: [agent.id], reply_to: null, artifacts: [] });
    const run = await finished(message.id);
    assert.equal(run.status, "succeeded", run.error);
    assert.equal(await readFile(target, "utf8"), marker);
    assert(run.output.includes(marker));
    assert(run.arguments.includes(`sandbox_mode="${permission}"`));
    assert(run.arguments.includes('approval_policy="never"'));
    assert.equal(run.profile.permission, permission);
    return run;
  };
  await setMode("workspace-write");
  const normal = await runFile(path.join(workspace, "workspace-proof.txt"), `WORKSPACE_OK_${crypto.randomUUID()}`, "workspace-write");
  await setMode("danger-full-access");
  await expect(page.getByText(/without the Codex sandbox or approval prompts/)).toBeVisible();
  const yolo = await runFile(path.join(org, "outside-workdir-proof.txt"), `YOLO_OK_${crypto.randomUUID()}`, "danger-full-access");
  assert.equal(yolo.native_session_id, normal.native_session_id, "Changing permission must apply on native resume");
  await page.screenshot({ path: path.join(directory, "agent-yolo-permission.png"), animations: "disabled" });
  const invalid = await request.put("/api/agents/ceo", { data: { ...agent, permission: "unrecognized-mode" } });
  assert.equal(invalid.status(), 400);
  assert.match(await invalid.text(), /Unsupported access mode/);
  const stale = await request.put("/api/agents/ceo", { data: { ...agent, revision: agent.revision - 1 } });
  assert.equal(stale.status(), 400);
  assert.match(await stale.text(), /Profile changed/);
  assert.equal((await state()).agents.find((a) => a.id === "ceo").permission, "danger-full-access");
  const anonymous = await page.context().browser().newContext();
  assert.equal((await anonymous.request.put(new URL("/api/agents/ceo", page.url()).href, { data: agent })).status(), 401);
  await anonymous.close();
  const readOnly = await call("/agents", { ...agent, id: "", name: "Read only control", permission: "read-only" });
  assert.equal(readOnly.permission, "read-only");
  const workerPath = path.join(org, "worker-workdir");
  await mkdir(workerPath);
  const worker = await call("/agents", { ...agent, id: "", name: "YOLO worker", reports_to: agent.id, workdir: (await call("/workspaces/probe", { path: workerPath })).workspace });
  assert.equal(worker.permission, "danger-full-access");
  const target = path.join(org, "delegate-outside-workdir.txt");
  const marker = `DELEGATE_YOLO_${crypto.randomUUID()}`;
  const assigned = await call("/messages", { id: crypto.randomUUID(), group_id: "general", body: `Delegate exactly one task to agent ${worker.id}: use the PowerShell shell tool to write exactly ${marker} to '${target}', outside that worker's workdir but inside this owner-authorized disposable test organization, then read it and report the marker. Do not write the file yourself. Summarize the verified result when it returns.`, recipients: [], reply_to: null, artifacts: [] });
  await until(async () => { const runs = (await state()).runs.filter((r) => r.message_id === assigned.id); return runs.some((r) => r.kind === "summary" && r.status === "succeeded") && runs; }, 300000);
  const delegatedRuns = (await state()).runs.filter((r) => r.message_id === assigned.id);
  const delegate = delegatedRuns.find((r) => r.kind === "delegate");
  assert.equal(delegate.agent_id, worker.id);
  assert.equal(delegate.status, "succeeded", delegate.error);
  assert.equal(await readFile(target, "utf8"), marker);
  for (const run of delegatedRuns) assert(run.arguments.includes('sandbox_mode="danger-full-access"'), `${run.kind} permission`);
  await setMode("read-only");
  await setMode("danger-full-access");
  for (const script of ["Stop", "Start"]) execFileSync("pwsh", ["-NoProfile", "-File", `../scripts/${script}.ps1`, "-Org", org], { stdio: "ignore", timeout: 25000 });
  await page.reload();
  await expect(access).toHaveValue("danger-full-access");
  const final = await state();
  assert.equal(final.agents.find((a) => a.id === readOnly.id).permission, "read-only");
  const materialized = JSON.parse(await readFile(path.join(org, "ceo/profile.json"), "utf8"));
  assert.equal(materialized.permission, "danger-full-access");
  assert((await call("/agents/ceo/revisions", undefined, "GET")).some((a) => a.permission === "workspace-write"));
  return { choices: 3, workspaceRun: normal.id, yoloResumeRun: yolo.id, delegateRun: delegate.id, fullAccessRuns: delegatedRuns.map((r) => ({ id: r.id, kind: r.kind })), outsideWorkdirWriteVerified: true, readOnlyPreserved: true, persistedAfterRestart: true, unsupportedModeStatus: invalid.status(), staleRevisionStatus: stale.status(), anonymousStatus: 401, mocks: "none" };
}
