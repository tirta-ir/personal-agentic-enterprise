import { createRequire } from 'node:module';
import { readFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(new URL('../frontend/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const [base, usersFile, output] = process.argv.slice(2);
assert(base && usersFile && output, 'Usage: node verify-mention-ui.mjs BASE_URL USERS_JSON OUTPUT_DIR');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.platform === 'win32' ? 'msedge' : undefined });
try {
  const context = await browser.newContext({ viewport: { width: 1200, height: 900 } });
  const users = JSON.parse(await readFile(usersFile, 'utf8'));
  assert.equal((await context.request.post(`${base}/api/login`, { data: { username: 'alice', password: users.alice } })).status(), 200);
  const state = await (await context.request.get(`${base}/api/state`)).json();
  const group = state.groups.find(group => group.id === 'general');
  assert(group);
  const eligible = state.agents.filter(agent => agent.enabled && state.group_access[group.id].participant_ids.includes(agent.id));
  assert(eligible.length > 0);
  const agent = eligible[0];
  const page = await context.newPage();
  const errors = [];
  let sent = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/messages') sent++; });
  await page.goto(`${base}/groups/general/chat`);
  const input = page.getByRole('textbox', { name: 'Message', exact: true });
  const picker = page.getByRole('listbox', { name: 'Mention an agent' });
  await input.fill('');
  await input.pressSequentially('@');
  await picker.waitFor();
  assert.equal(await picker.getByRole('option').count(), eligible.length);
  if (eligible.length > 1) {
    await input.press('ArrowDown');
    assert.equal(await picker.getByRole('option').nth(1).getAttribute('aria-selected'), 'true');
    await input.press('ArrowUp');
  }
  await input.press('Enter');
  assert.equal(await input.inputValue(), `@${agent.id} `);
  assert.equal(await picker.count(), 0);
  await input.fill(`Hello @${agent.id}`);
  await picker.waitFor();
  await picker.getByRole('option').filter({ hasText: `@${agent.id} ·` }).click();
  assert.equal(await input.inputValue(), `Hello @${agent.id} `);
  await input.fill('Before @ after');
  await input.press('Home');
  for (let i = 0; i < 8; i++) await input.press('ArrowRight');
  await picker.waitFor();
  await input.press('Tab');
  assert.equal(await input.inputValue(), `Before @${agent.id} after`);
  await input.fill('@zzzz-no-agent');
  await page.getByText('No matching agents in this room.', { exact: true }).waitFor();
  await input.press('Enter');
  assert.equal(await input.inputValue(), '@zzzz-no-agent');
  await input.press('Escape');
  assert.equal(await picker.count(), 0);
  await input.fill('alice@example.com');
  assert.equal(await picker.count(), 0);
  await input.fill('/us');
  await page.getByRole('listbox', { name: 'Chat commands' }).waitFor();
  await input.press('Tab');
  assert.equal(await input.inputValue(), '/usage');
  await input.fill('');
  await page.getByRole('button', { name: 'Mention an agent', exact: true }).click();
  await picker.waitFor();
  for (const width of [1200, 375]) {
    await page.setViewportSize({ width, height: 900 });
    const panel = await picker.boundingBox();
    const box = await input.boundingBox();
    assert(panel.y >= 0 && panel.y + panel.height <= box.y);
    assert(panel.x >= 0 && panel.x + panel.width <= width);
    await page.screenshot({ path: resolve(output, `mentions-${width}.png`), animations: 'disabled' });
  }
  await input.fill('');
  await page.setViewportSize({ width: 1200, height: 900 });
  const scoped = state.groups.find(candidate => candidate.id !== 'general' && candidate.member_ids?.length);
  assert(scoped, 'Verification needs an existing room with explicit agent membership');
  await page.getByRole('button', { name: scoped.name, exact: true }).click();
  await input.fill('@');
  await picker.waitFor();
  const scopedAgents = state.agents.filter(agent => agent.enabled && state.group_access[scoped.id].participant_ids.includes(agent.id));
  assert.equal(await picker.getByRole('option').count(), scopedAgents.length);
  for (const scopedAgent of scopedAgents) assert((await picker.innerText()).includes(`@${scopedAgent.id}`));
  await input.fill('');
  assert.equal(sent, 0, 'Picking an agent must not send a message');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ typingOpens: true, eligibleAgents: eligible.length, scopedAgents: scopedAgents.length, filtering: true, keyboard: true, caretInsertion: true, emailIgnored: true, noMatch: true, slashPreserved: true, buttonPreserved: true, responsiveWidths: [1200,375], messagesSent: sent, pageErrors: errors }));
  await context.request.post(`${base}/api/logout`);
} finally { await browser.close(); }
