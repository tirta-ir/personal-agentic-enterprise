  await page.screenshot({ path: resolve(dir, 'runtime-metadata.png') });
  await api('/runtimes/' + registered.id, { name: '', description: '' }, 'PUT', testTenant.id, 400);
  await api('/runtimes/' + registered.id, { name: 'X', description: '', root: '/' }, 'PUT', testTenant.id, 400);
