  assert.deepEqual(metadata(await api('/runtimes')), metadata(before.runtimes));
  assert.deepEqual(errors, []);
  const proof = { runtimeNamesOnly: true, creationOrder: 'runtime, detected harness, workdir, profile', invalidWorkdirRejected: true,
    createdOnRegisteredWorker: true, runtimeSwitchPersisted: true, oldWorkdirCleared: true, workdirReattached: true,
    projectInheritanceChecked: Boolean(projectGroup), metadataPersisted: true, invalidMetadataRejected: true, crossWorkspaceRejected: true, anonymousRejected: true, revokedRejected: true,
    originalAgentsAndGroupsPreserved: true, workerMetadataPreserved: true, browserErrors: errors, mocks: false };
  await writeFile(resolve(dir, 'proof.json'), JSON.stringify(proof, null, 2)); console.log(JSON.stringify(proof));
